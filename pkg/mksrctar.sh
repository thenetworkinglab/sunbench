# mksrctar.sh -- build the source tarball, for SunOS 4 / Solaris 1.x (which
# has no pkgadd, but does ship a working K&R cc) and for general distribution.
#
#     sh pkg/mksrctar.sh 2026.11.22-4
#
# On the target:
#     tar -xf sunbench-<version>-src.tar
#     cd sunbench-<version>
#     ./configure && make && make install
#
# Plain (uncompressed) tar so SunOS 4's stock tar can read it without gzip.
#
VERSION=${1:-2026.11.22-4}
NAME=sunbench-${VERSION}
STAGE=/tmp/$NAME
OUT=`pwd`/${NAME}-src.tar

rm -rf "$STAGE"
mkdir -p "$STAGE/src" || exit 1

cp configure Makefile sunbench.1 "$STAGE/" || exit 1
cp README.md CHANGELOG.md CLAUDE.md LICENSE NOTICE "$STAGE/" 2>/dev/null
cp src/*.c src/*.h "$STAGE/src/" || exit 1
rm -f "$STAGE/src/config.h"        # generated by configure on the target
rm -f "$STAGE/src/config.cflags"   # likewise
chmod 755 "$STAGE/configure"

rm -f "$OUT"
# On macOS, bsdtar injects AppleDouble (._*) files and pax extended headers
# that Solaris/SunOS 4 tar cannot read.  Force plain ustar and strip the mac
# metadata there; on Solaris the native tar already does the right thing.
TARFLAGS=""
if [ "`uname -s`" = "Darwin" ]; then
    COPYFILE_DISABLE=1; export COPYFILE_DISABLE
    TARFLAGS="--no-mac-metadata --no-xattrs --format ustar"
fi
( cd /tmp && tar $TARFLAGS -cf "$OUT" "$NAME" ) || exit 1
rm -rf "$STAGE"

echo "created ${NAME}-src.tar"
echo "build on target:  tar -xf ${NAME}-src.tar && cd $NAME && ./configure && make"
